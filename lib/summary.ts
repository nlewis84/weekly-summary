async function fetchLinearData(
  windowStart: Date,
  windowEnd: Date,
  windowStartISO: string,
  windowEndISO: string
) {
  const key = process.env.LINEAR_API_KEY;
  if (!key)
    return {
      completedIssues: [],
      completedProjects: [],
      workedOnIssues: [],
      createdIssues: [],
      commentedIssues: [],
      userName: null,
    };

  const headers = { Authorization: key, "Content-Type": "application/json" };

  try {
    const userData = await fetchLinearPage(headers, LINEAR_USER_QUERY, {});
    const userId = (userData as { viewer?: { id?: string; name?: string } })
      ?.viewer?.id;
    if (!userId) throw new Error("No Linear user ID");

    const userName =
      (userData as { viewer?: { name?: string } })?.viewer?.name ?? null;

    const [
      assignedCompleted,
      windowCompleted,
      completedProjects,
      rawWorkedOn,
      createdIssues,
      rawComments,
    ] = await Promise.all([
      softFetchLinear("assigned completed issues", () =>
        fetchAllLinearIssues(headers, LINEAR_COMPLETED_QUERY, {
          assigneeId: userId,
          completedAfter: windowStartISO,
          completedBefore: windowEndISO,
        })
      ),
      softFetchLinear("issues completed in window", () =>
        fetchAllLinearIssues(headers, LINEAR_COMPLETED_BY_ACTOR_QUERY, {
          completedAfter: windowStartISO,
          completedBefore: windowEndISO,
        })
      ),
      softFetchLinear("completed projects", () =>
        fetchAllLinearProjects(headers, LINEAR_COMPLETED_PROJECTS_QUERY, {
          userId,
          completedAfter: windowStartISO,
          completedBefore: windowEndISO,
        })
      ),
      softFetchLinear("worked-on issues", () =>
        fetchAllLinearIssues(headers, LINEAR_WORKED_ON_QUERY, {
          assigneeId: userId,
          updatedAfter: windowStartISO,
        })
      ),
      softFetchLinear("created issues", () =>
        fetchAllLinearIssues(headers, LINEAR_CREATED_QUERY, {
          creatorId: userId,
          createdAfter: windowStartISO,
          createdBefore: windowEndISO,
        })
      ),
      softFetchLinear("comments", () =>
        fetchAllLinearComments(headers, LINEAR_COMMENTS_QUERY, {
          userId,
          createdAfter: windowStartISO,
          createdBefore: windowEndISO,
        })
      ),
    ]);

    // Only projects that actually shipped — "Incomplete" is a completed-type
    // status in Linear, so completedAt alone would count abandoned work.
    const deliveredProjects = completedProjects.filter(isDeliveredProject);

    // Issues you moved to Done yourself, whoever they were assigned to.
    const seenCompletedIds = new Set(
      assignedCompleted.map((i) => i.id).filter(Boolean) as string[]
    );
    const completedIssues = [
      ...assignedCompleted,
      ...windowCompleted.filter((issue) => {
        if (issue.id && seenCompletedIds.has(issue.id)) return false;
        return completedByActorId(issue, windowStart, windowEnd) === userId;
      }),
    ];

    const workedOnIssues = rawWorkedOn.filter((issue) => {
      const stateName = issue.state?.name ?? "";
      const stateType = issue.state?.type ?? "";
      const completedAt = issue.completedAt
        ? new Date(issue.completedAt)
        : null;
      if (stateName === "In Progress" || stateName === "In Review") return true;
      if (stateName === "Done" || stateType === "completed") {
        if (!completedAt) return false;
        return completedAt >= windowStart && completedAt <= windowEnd;
      }
      return false;
    });

    const seenIssueIds = new Set<string>();
    const commentedIssues = rawComments
      .filter((c) => {
        const issueId = c.issue?.id;
        if (!issueId || seenIssueIds.has(issueId)) return false;
        seenIssueIds.add(issueId);
        return true;
      })
      .map((c) => ({
        identifier: c.issue?.identifier ?? "",
        title: c.issue?.title ?? "",
        url: c.issue?.url ?? null,
        project: c.issue?.project?.name ?? null,
        state: c.issue?.state?.name ?? c.issue?.state?.type ?? null,
      }));

    return {
      completedIssues,
      completedProjects: deliveredProjects,
      workedOnIssues,
      createdIssues,
      commentedIssues,
      userName,
    };
  } catch {
    return {
      completedIssues: [],
      completedProjects: [],
      workedOnIssues: [],
      createdIssues: [],
      commentedIssues: [],
      userName: null,
    };
  }
}

/**
 * GitHub search returns at most 100 items per page. A single unpaginated
 * request silently truncates: a week with 200 reviewed PRs came back as 100
 * candidates, so the review count was capped at whatever survived filtering.
 * Page until the result set is exhausted, bounded by the 1,000-result ceiling
 * the search API enforces.
 */
const SEARCH_PAGE_SIZE = 100;
const SEARCH_MAX_PAGES = 10;

async function searchAllIssues(
  query: string,
  headers: HeadersInit,
  priority: SearchPriority
): Promise<Array<Record<string, unknown>>> {
  const items: Array<Record<string, unknown>> = [];
  for (let page = 1; page <= SEARCH_MAX_PAGES; page += 1) {
    const res = await searchRequest(
      `${GITHUB_API_BASE}/search/issues?q=${query}&per_page=${SEARCH_PAGE_SIZE}&page=${page}`,
      headers,
      { priority }
    );
    if (!res.ok) break;
    const data = (await res.json()) as {
      items?: Array<Record<string, unknown>>;
      total_count?: number;
    };
    const batch = data.items ?? [];
    items.push(...batch);
    if (batch.length < SEARCH_PAGE_SIZE) break;
    if (
      typeof data.total_count === "number" &&
      items.length >= data.total_count
    )
      break;
  }
  return items;
}

/**
 * `updated:A..B` — bounding both ends keeps the result set under the search
 * API's 1,000-result ceiling. A review always bumps the PR's updated_at, so a
 * PR reviewed inside the window was updated inside it too. Bounds come from the
 * UTC dates, which only ever widens the range; exact timestamps are filtered
 * afterwards.
 */
function dateRange(startISO: string, endISO: string): string {
  return `${startISO.split("T")[0]}..${endISO.split("T")[0]}`;
}

