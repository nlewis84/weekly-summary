type CandidateReviewPR = {
  pull_request?: { url?: string };
  html_url?: string;
  title?: string;
  [k: string]: unknown;
};

export type ReviewedPR = CandidateReviewPR & {
  reviewed_at: string;
  review_state: string;
};

/**
 * GitHub applies a secondary rate limit to concurrent requests, and these fans
 * are now per-candidate over a fully paginated search — up to a thousand PRs.
 * Firing them all at once earns a wall of 403s, which this code reads as "no
 * review found" and silently turns into a zero. Bound the burst instead.
 */
const GITHUB_FETCH_CONCURRENCY = 6;

async function mapWithConcurrency<T, R>(
  items: T[],
  limit: number,
  fn: (item: T) => Promise<R>
): Promise<R[]> {
  const results = new Array<R>(items.length);
  let next = 0;
  const workers = Array.from(
    { length: Math.min(limit, items.length) },
    async () => {
      while (next < items.length) {
        const i = next++;
        results[i] = await fn(items[i]!);
      }
    }
  );
  await Promise.all(workers);
  return results;
}

/**
 * Keeps only PRs where the user submitted a review (comment, request changes, or approve) within the time window.
 * Attaches reviewed_at (first non-PENDING submitted_at by user in window) and review_state.
 */
async function filterReviewsBySubmittedInWindow(
  candidatePRs: CandidateReviewPR[],
  windowStart: Date,
  windowEnd: Date,
  username: string,
  headers: HeadersInit
): Promise<ReviewedPR[]> {
  const results = await mapWithConcurrency(
    candidatePRs,
    GITHUB_FETCH_CONCURRENCY,
    async (pr) => {
      const reviewsUrl = pr.pull_request?.url
        ? `${pr.pull_request.url}/reviews`
        : null;
      if (!reviewsUrl) return null;
      try {
        const res = await fetchWithRetry(reviewsUrl, { headers });
        if (!res.ok) return null;
        const reviews = (await res.json()) as Array<{
          user?: { login?: string };
          state?: string;
          submitted_at?: string | null;
        }>;
        const mine = reviews
          .filter(
            (r) =>
              r.user?.login === username &&
              r.submitted_at != null &&
              r.state !== "PENDING" &&
              new Date(r.submitted_at) >= windowStart &&
              new Date(r.submitted_at) <= windowEnd
          )
          .sort(
            (a, b) =>
              new Date(a.submitted_at!).getTime() -
              new Date(b.submitted_at!).getTime()
          );
        const first = mine[0];
        if (!first?.submitted_at) return null;
        return {
          ...pr,
          reviewed_at: first.submitted_at,
          review_state: first.state ?? "COMMENTED",
        };
      } catch {
        return null;
      }
    }
  );
  return results.filter((pr): pr is ReviewedPR => pr != null);
}

