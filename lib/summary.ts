/**
 * Local midnight for the calendar day of `now`.
 */
export function startOfLocalDay(now: Date): Date {
  return new Date(now.getFullYear(), now.getMonth(), now.getDate(), 0, 0, 0, 0);
}

/**
 * Resolve the Today window as capture-to-capture:
 * - Live view: since the most recent capture → now
 * - Capture / re-capture: since the previous day's capture → now
 *   (so updating today's snapshot refreshes the full open period)
 * Falls back to local midnight when there is no prior capture.
 */
export function resolveTodayWindow(
  now: Date,
  options: { forCapture?: boolean } = {}
): { windowStart: Date; windowEnd: Date } {
  const windowEnd = now;
  const today = localDateString(now);

  if (options.forCapture) {
    const prev = getMostRecentSnapshot(today);
    if (prev) {
      return { windowStart: prev.capturedAt, windowEnd };
    }
    return { windowStart: startOfLocalDay(now), windowEnd };
  }

  const latest = getMostRecentSnapshot();
  if (latest) {
    return { windowStart: latest.capturedAt, windowEnd };
  }
  return { windowStart: startOfLocalDay(now), windowEnd };
}

export function getWindowStart(
  now: Date,
  todayMode: boolean,
  yesterdayMode = false
): Date {
  if (yesterdayMode) {
    const yesterday = new Date(now);
    yesterday.setDate(now.getDate() - 1);
    return startOfLocalDay(yesterday);
  }
  if (todayMode) {
    // Prefer resolveTodayWindow for capture-to-capture; this remains the
    // calendar-day fallback used by weekly math and tests.
    return startOfLocalDay(now);
  }
  const day = now.getDay();
  const daysSinceSaturday = (day + 1) % 7;
  const saturday = new Date(now);
  saturday.setDate(now.getDate() - daysSinceSaturday);
  saturday.setHours(0, 0, 0, 0);
  return saturday;
}

export function getWindowEnd(
  now: Date,
  todayMode = false,
  yesterdayMode = false
): Date {
  if (yesterdayMode) {
    const yesterday = new Date(now);
    yesterday.setDate(now.getDate() - 1);
    return new Date(
      yesterday.getFullYear(),
      yesterday.getMonth(),
      yesterday.getDate(),
      23,
      59,
      59,
      999
    );
  }
  if (todayMode) {
    return now;
  }
  return new Date(
    now.getFullYear(),
    now.getMonth(),
    now.getDate(),
    23,
    59,
    59,
    999
  );
}

/**
 * Full Sat–Fri window for a Friday week-ending date (YYYY-MM-DD).
 */
export function getWindowForWeekEnding(weekEnding: string): {
  windowStart: Date;
  windowEnd: Date;
} {
  if (!/^\d{4}-\d{2}-\d{2}$/.test(weekEnding)) {
    throw new Error(
      `Invalid week-ending date: ${weekEnding} (expected YYYY-MM-DD)`
    );
  }
  const [y, m, d] = weekEnding.split("-").map(Number);
  const windowEnd = new Date(y, m - 1, d, 23, 59, 59, 999);
  if (Number.isNaN(windowEnd.getTime())) {
    throw new Error(`Invalid week-ending date: ${weekEnding}`);
  }
  if (windowEnd.getDay() !== 5) {
    const dayName = windowEnd.toLocaleDateString("en-US", { weekday: "long" });
    throw new Error(
      `--week must be a Friday (week-ending date). Got ${weekEnding} (${dayName}).`
    );
  }
  const windowStart = new Date(y, m - 1, d - 6, 0, 0, 0, 0);
  return { windowStart, windowEnd };
}

export function parseCheckIns(checkInsText: string): CheckIn[] {
  if (!checkInsText?.trim()) return [];

  const skipPatterns = [
    /^Apollos Engineering:/i,
    /^Nathan Lewis/i,
    /^File…/,
    /^PR Reviews?$/i,
    /^> /,
  ];

  const isSkipLine = (line: string) => {
    const t = line.trim();
    if (!t) return true;
    return skipPatterns.some((p) => p.test(t));
  };

  const lines = checkInsText.split("\n");
  const entries: CheckIn[] = [];
  let currentDay: string | null = null;
  let currentContent: string[] = [];

  const dayRegex =
    /^(Monday|Tuesday|Wednesday|Thursday|Friday|Saturday|Sunday|Yesterday|Dec \d+|December \d+)[:.]?\s*(.*)$/i;

  for (const line of lines) {
    if (isSkipLine(line)) continue;

    const m = line.match(dayRegex);
    if (m) {
      if (currentDay && currentContent.length > 0) {
        const content = currentContent.join("\n").trim();
        if (content) entries.push({ day: currentDay, content });
      }
      currentDay = m[1];
      currentContent = m[2]?.trim() ? [m[2].trim()] : [];
    } else if (currentDay && !isSkipLine(line)) {
      currentContent.push(line);
    }
  }

  if (currentDay && currentContent.length > 0) {
    const content = currentContent.join("\n").trim();
    if (content) entries.push({ day: currentDay, content });
  }

  return entries.length > 0
    ? entries
    : [{ day: "Check-ins", content: checkInsText.trim() }];
}

async function fetchLinearPage(
  headers: Record<string, string>,
  query: string,
  variables: Record<string, unknown>
) {
  const res = await fetch(LINEAR_API_BASE, {
    method: "POST",
    headers,
    body: JSON.stringify({ query, variables }),
  });
  if (!res.ok) throw new Error(`Linear API: ${res.status}`);
  const data = await res.json();
  if (data.errors) throw new Error(`Linear: ${JSON.stringify(data.errors)}`);
  return data.data;
}

