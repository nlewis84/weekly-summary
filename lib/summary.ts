type PrRef = { repo: string; number: number };

/**
 * Count commits authored by `username` within the window across:
 *   1. The default branch of each configured repo (`/repos/.../commits`)
 *   2. Every branch attached to one of the user's PRs (open, draft, or merged)
 *      via `/repos/.../pulls/{n}/commits`
 *
 * Commits are deduped by SHA so a commit that exists on both a PR branch and
 * the default branch (after merge) is only counted once.
 */
async function fetchCommitsPushed(
  username: string,
  headers: Record<string, string>,
  windowStart: Date,
  windowEnd: Date,
  userPRs: PrRef[]
): Promise<{ total: number; reposWithCommits: string[] }> {
  const { owner, repos } = getCommitRepos();
  const trackedRepos = new Set(repos);
  if (repos.length === 0) return { total: 0, reposWithCommits: [] };

  const since = windowStart.toISOString();
  const until = windowEnd.toISOString();

  const seen = new Map<string, string>(); // sha -> repo

  const inWindow = (iso?: string | null): boolean => {
    if (!iso) return false;
    const t = new Date(iso).getTime();
    return t >= windowStart.getTime() && t <= windowEnd.getTime();
  };

  try {
    const defaultBranchResults = await Promise.all(
      repos.map(async (repo) => {
        const collected: Array<{ sha: string; date: string | null }> = [];
        let page = 1;
        const perPage = 100;
        let hasMore = true;
        while (hasMore) {
          const url = `${GITHUB_API_BASE}/repos/${owner}/${repo}/commits?author=${username}&since=${since}&until=${until}&per_page=${perPage}&page=${page}`;
          const res = await fetch(url, { headers });
          if (!res.ok) return { repo, commits: collected };
          const commits = (await res.json()) as Array<{
            sha?: string;
            commit?: { author?: { date?: string } };
          }>;
          if (!Array.isArray(commits)) return { repo, commits: collected };
          for (const c of commits) {
            if (c.sha)
              collected.push({
                sha: c.sha,
                date: c.commit?.author?.date ?? null,
              });
          }
          hasMore = commits.length === perPage;
          page += 1;
        }
        return { repo, commits: collected };
      })
    );

    for (const { repo, commits } of defaultBranchResults) {
      for (const c of commits) {
        if (!seen.has(c.sha)) seen.set(c.sha, repo);
      }
    }

    const prCommitResults = await Promise.all(
      userPRs
        .filter((p) => trackedRepos.has(p.repo))
        .map(async ({ repo, number }) => {
          const collected: Array<{ sha: string; date: string | null }> = [];
          let page = 1;
          const perPage = 100;
          let hasMore = true;
          while (hasMore) {
            const url = `${GITHUB_API_BASE}/repos/${owner}/${repo}/pulls/${number}/commits?per_page=${perPage}&page=${page}`;
            const res = await fetch(url, { headers });
            if (!res.ok) return { repo, commits: collected };
            const commits = (await res.json()) as Array<{
              sha?: string;
              author?: { login?: string } | null;
              commit?: {
                author?: { name?: string; email?: string; date?: string };
              };
            }>;
            if (!Array.isArray(commits)) return { repo, commits: collected };
            for (const c of commits) {
              const date = c.commit?.author?.date ?? null;
              if (!inWindow(date)) continue;
              const matchesUser =
                c.author?.login === username ||
                c.commit?.author?.email
                  ?.toLowerCase()
                  .includes(username.toLowerCase()) ||
                c.commit?.author?.name
                  ?.toLowerCase()
                  .includes(username.toLowerCase());
              if (!matchesUser) continue;
              if (c.sha) collected.push({ sha: c.sha, date });
            }
            hasMore = commits.length === perPage;
            page += 1;
          }
          return { repo, commits: collected };
        })
    );

    for (const { repo, commits } of prCommitResults) {
      for (const c of commits) {
        if (!seen.has(c.sha)) seen.set(c.sha, repo);
      }
    }

    const total = seen.size;
    const reposWithCommits = [...new Set([...seen.values()])].sort();
    return { total, reposWithCommits };
  } catch {
    return { total: 0, reposWithCommits: [] };
  }
}

const COMMENT_PAGE_SIZE = 100;

/** Issue comments left by `username` on one PR, bounded to the window at both ends. */
async function countMyComments(
  commentsUrl: string,
  username: string,
  windowStart: Date,
  windowEnd: Date,
  headers: HeadersInit
): Promise<number> {
  let total = 0;
  let page = 1;
  try {
    while (true) {
      const sep = commentsUrl.includes("?") ? "&" : "?";
      const res = await fetchWithRetry(
        `${commentsUrl}${sep}per_page=${COMMENT_PAGE_SIZE}&page=${page}`,
        { headers }
      );
      if (!res.ok) return total;
      const comments = (await res.json()) as Array<{
        user?: { login?: string };
        created_at?: string;
      }>;
      if (!Array.isArray(comments)) return total;
      for (const c of comments) {
        if (c.user?.login !== username || c.created_at == null) continue;
        const at = new Date(c.created_at);
        if (at >= windowStart && at <= windowEnd) total += 1;
      }
      if (comments.length < COMMENT_PAGE_SIZE) return total;
      page += 1;
    }
  } catch {
    return total;
  }
}

/**
 * Reviews the user submitted inside a window, latency-enriched — the same
 * pipeline the live weekly run uses. Exported so backfills of saved summaries
 * recompute from identical logic rather than a second implementation that can
 * drift.
 */
export async function fetchReviewsInWindow(
  windowStart: Date,
  windowEnd: Date,
  username: string,
  headers: HeadersInit,
  options: { searchUntil?: Date } = {}
): Promise<ReviewEntry[]> {
  // Backfills widen the *search* bound (a PR reviewed in-window can be updated
  // long after it) while the submitted_at filter below stays on the real window.
  const searchUntil = options.searchUntil ?? windowEnd;
  const items = await searchAllIssues(
    `reviewed-by:${username}+type:pr+updated:${dateRange(
      windowStart.toISOString(),
      searchUntil.toISOString()
    )}`,
    headers,
    "high"
  );
  const reviewed = await filterReviewsBySubmittedInWindow(
    filterApollosPRs(items),
    windowStart,
    windowEnd,
    username,
    headers
  );
  return enrichReviewsWithLatency(reviewed, username, headers);
}

/** PRs the user authored that were created or touched on or after the window's start day. */
export async function searchAuthoredPRs(
  windowStart: Date,
  windowEnd: Date,
  username: string,
  headers: HeadersInit
): Promise<Array<Record<string, unknown>>> {
  const range = dateRange(windowStart.toISOString(), windowEnd.toISOString());
  const [created, updated] = await Promise.all([
    searchAllIssues(
      `author:${username}+type:pr+created:${range}`,
      headers,
      "high"
    ),
    searchAllIssues(
      `author:${username}+type:pr+updated:${range}`,
      headers,
      "high"
    ),
  ]);
  const seen = new Set<string>();
  return [...created, ...updated].filter((pr) => {
    const url = pr.html_url as string | undefined;
    if (!url || seen.has(url)) return false;
    seen.add(url);
    return url.includes("ApollosProject");
  });
}

/** Issue comments by the user, across every given PR, bounded to the window. */
export async function countPrCommentsInWindow(
  commentsUrls: string[],
  username: string,
  windowStart: Date,
  windowEnd: Date,
  headers: HeadersInit
): Promise<number> {
  const unique = [...new Set(commentsUrls.filter(Boolean))];
  const counts = await mapWithConcurrency(
    unique,
    GITHUB_FETCH_CONCURRENCY,
    (url) => countMyComments(url, username, windowStart, windowEnd, headers)
  );
  return counts.reduce((a, b) => a + b, 0);
}

async function fetchGitHubData(
  windowStart: Date,
  windowStartISO: string,
  windowEnd: Date
) {
  const token = process.env.GITHUB_TOKEN;
  const username = process.env.GITHUB_USERNAME ?? "nlewis84";
  if (!token)
    return {
      prs: [],
      reviews: [],
      comments: 0,
      commits_pushed: 0,
      reposWithCommits: [],
    };

  const headers = {
    Authorization: `Bearer ${token}`,
    Accept: "application/vnd.github+json",
    "X-GitHub-Api-Version": "2022-11-28",
  };
  try {
    // "high": these three are what the page exists to show, so they keep the
    // smallest reserve and the monthly search yields to them.
    const range = dateRange(windowStartISO, windowEnd.toISOString());
    const [prsCreatedItems, prsUpdatedItems, reviewItems] = await Promise.all([
      searchAllIssues(
        `author:${username}+type:pr+created:${range}`,
        headers,
        "high"
      ),
      searchAllIssues(
        `author:${username}+type:pr+updated:${range}`,
        headers,
        "high"
      ),
      searchAllIssues(
        `reviewed-by:${username}+type:pr+updated:${range}`,
        headers,
        "high"
      ),
    ]);

    const allPRs = [...prsCreatedItems, ...prsUpdatedItems];
    const seen = new Set<string>();
    const uniquePRs = allPRs.filter((pr: { html_url?: string }) => {
      if (!pr.html_url || seen.has(pr.html_url)) return false;
      seen.add(pr.html_url);
      return pr.html_url.includes("ApollosProject");
    });

    const prDetails = await Promise.all(
      uniquePRs.map(
        async (pr: {
          pull_request?: { url?: string };
          html_url?: string;
          merged_at?: string;
          state?: string;
          additions?: number;
          deletions?: number;
          changed_files?: number;
        }) => {
          if (pr.pull_request?.url) {
            try {
              const r = await fetchWithRetry(pr.pull_request.url, { headers });
              if (r.ok) {
                const d = await r.json();
                return {
                  ...pr,
                  merged_at: d.merged_at,
                  state: d.state,
                  additions: d.additions ?? 0,
                  deletions: d.deletions ?? 0,
                  changed_files: d.changed_files ?? 0,
                };
              }
            } catch {
              /* fetch failed, use original pr */
            }
          }
          return pr;
        }
      )
    );

    const userPrRefs: PrRef[] = prDetails
      .map((pr: { html_url?: string }) => {
        const m = pr.html_url?.match(/ApollosProject\/([^/]+)\/pull\/(\d+)/);
        if (!m) return null;
        return { repo: m[1], number: Number(m[2]) };
      })
      .filter((p): p is PrRef => p != null);

    const [reviewedPRs, commitsResult] = await Promise.all([
      filterReviewsBySubmittedInWindow(
        filterApollosPRs(reviewItems),
        windowStart,
        windowEnd,
        username,
        headers
      ),
      fetchCommitsPushed(username, headers, windowStart, windowEnd, userPrRefs),
    ]);

    const reviews = await enrichReviewsWithLatency(
      reviewedPRs,
      username,
      headers
    );

    // Every PR you authored or reviewed, deduped. This used to be capped at the
    // first 20, which in a busy week meant only authored PRs were ever looked
    // at and every comment left on someone else's PR went uncounted.
    const totalComments = await countPrCommentsInWindow(
      ([...prDetails, ...reviewedPRs] as Array<{ comments_url?: string }>)
        .map((pr) => pr.comments_url)
        .filter((u): u is string => !!u),
      username,
      windowStart,
      windowEnd,
      headers
    );

    return {
      prs: prDetails,
      reviews,
      comments: totalComments,
      commits_pushed: commitsResult.total,
      reposWithCommits: commitsResult.reposWithCommits,
    };
  } catch (err) {
    // A rate-limited run must not be reported as a quiet zero. These numbers are
    // shown as the day's work and can be written into a saved weekly summary, so
    // "we could not ask" has to surface as an error, not as "you did nothing".
    if (err instanceof SearchBudgetError) throw err;
    return {
      prs: [],
      reviews: [],
      comments: 0,
      commits_pushed: 0,
      reposWithCommits: [],
    };
  }
}

function categorizePRs<T extends { merged_at?: string | null; state?: string }>(
  prs: T[],
  windowStart: Date,
  windowEnd: Date
): { merged: T[]; open: T[] } {
  // The candidate search has no upper bound on date, so a backfilled week would
  // otherwise count PRs merged after that week had already ended.
  const merged = prs.filter((pr) => {
    if (!pr.merged_at) return false;
    const at = new Date(pr.merged_at);
    return at >= windowStart && at <= windowEnd;
  });
  const open = prs.filter((pr) => pr.state === "open" && !pr.merged_at);
  return { merged, open };
}

function groupPRsByRepo(
  prs: Array<{ html_url?: string; url?: string; repo?: string | null }>
) {
  const grouped: Record<string, unknown[]> = {};
  for (const pr of prs) {
    const m = (pr.html_url ?? pr.url)?.match(/ApollosProject\/([^/]+)/);
    const repo = pr.repo ?? (m ? m[1] : "unknown");
    if (!grouped[repo]) grouped[repo] = [];
    grouped[repo].push(pr);
  }
  return grouped;
}

