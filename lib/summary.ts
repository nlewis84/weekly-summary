export async function runSummary(options: {
  todayMode: boolean;
  yesterdayMode?: boolean;
  /** Friday week-ending date (YYYY-MM-DD) for backfilling a past week */
  weekEnding?: string;
  checkInsText: string;
  outputDir: string | null;
  /** Capture path: window starts at the previous day's capture. */
  forCapture?: boolean;
}): Promise<RunSummaryResult> {
  const {
    todayMode,
    yesterdayMode = false,
    weekEnding: weekEndingOpt,
    checkInsText,
    forCapture = false,
  } = options;

  let windowStart: Date;
  let windowEnd: Date;
  let weekEnding: string;

  if (weekEndingOpt) {
    if (todayMode || yesterdayMode) {
      throw new Error("Cannot combine --week with --today or --yesterday");
    }
    const window = getWindowForWeekEnding(weekEndingOpt);
    windowStart = window.windowStart;
    windowEnd = window.windowEnd;
    weekEnding = weekEndingOpt;
  } else {
    const now = new Date();
    if (todayMode) {
      const window = resolveTodayWindow(now, { forCapture });
      windowStart = window.windowStart;
      windowEnd = window.windowEnd;
    } else {
      windowStart = getWindowStart(now, todayMode, yesterdayMode);
      windowEnd = getWindowEnd(now, todayMode, yesterdayMode);
    }
    // Use Friday of the week (not UTC date) so filenames stay consistent across timezones
    const refDate = yesterdayMode
      ? (() => {
          const d = new Date(now);
          d.setDate(now.getDate() - 1);
          return d;
        })()
      : now;
    const weekStart = getWindowStart(refDate, false);
    const fridayOfWeek = new Date(weekStart);
    fridayOfWeek.setDate(weekStart.getDate() + 6);
    weekEnding = `${fridayOfWeek.getFullYear()}-${String(fridayOfWeek.getMonth() + 1).padStart(2, "0")}-${String(fridayOfWeek.getDate()).padStart(2, "0")}`;
  }

  const windowStartISO = windowStart.toISOString();
  const windowEndISO = windowEnd.toISOString();

  const [linearData, githubData] = await Promise.all([
    fetchLinearData(windowStart, windowEnd, windowStartISO, windowEndISO),
    fetchGitHubData(windowStart, windowStartISO, windowEnd),
  ]);

  const checkIns = parseCheckIns(checkInsText);
  const prCategories = categorizePRs(
    githubData.prs as Array<{
      merged_at?: string | null;
      state?: string;
      additions?: number;
      deletions?: number;
      changed_files?: number;
    }>,
    windowStart,
    windowEnd
  );
  // PRs/reviews plus any tracked repo where you pushed commits (commit-only work)
  const prsAndReviews = [...githubData.prs, ...githubData.reviews] as Array<{
    html_url?: string;
    url?: string;
    repo?: string | null;
  }>;
  const prsByRepo = groupPRsByRepo(prsAndReviews);
  const commitRepos = githubData.reposWithCommits ?? [];
  const repos = [
    ...new Set([...Object.keys(prsByRepo), ...commitRepos]),
  ].sort();

  const volume = sumVolume(prCategories.merged);
  const latencyValues = githubData.reviews
    .map((r: ReviewEntry) => r.latency_hours)
    .filter((h): h is number => typeof h === "number");
  const medianLatency = median(latencyValues);

  const stats: Stats = {
    prs_merged: prCategories.merged.length,
    prs_total: githubData.prs.length,
    pr_reviews: githubData.reviews.length,
    pr_comments: githubData.comments,
    commits_pushed: githubData.commits_pushed ?? 0,
    linear_completed:
      linearData.completedIssues.length + linearData.completedProjects.length,
    linear_projects_completed: linearData.completedProjects.length,
    linear_worked_on: linearData.workedOnIssues.length,
    linear_issues_created: linearData.createdIssues.length,
    linear_comments: linearData.commentedIssues.length,
    repos,
    lines_added: volume.lines_added,
    lines_deleted: volume.lines_deleted,
    files_changed: volume.files_changed,
    median_review_latency_hours: medianLatency,
  };

  const terminalOutput = buildTerminalOutput(
    linearData,
    githubData,
    checkIns,
    prCategories,
    repos,
    volume,
    medianLatency
  );

  const payload: Payload = {
    meta: {
      generated_at: new Date().toISOString(),
      window_start: windowStartISO,
      window_end: windowEndISO,
      week_ending: weekEnding,
      source_of_truth:
        "End-of-year review and career narrative. Document leadership, ownership, mentoring, cross-team work, and technical impact.",
    },
    stats,
    linear: {
      completed_issues: linearData.completedIssues.map(
        (i: LinearIssueNode) => ({
          identifier: i.identifier ?? "",
          title: i.title ?? "",
          project: i.project?.name ?? null,
          url: i.url ?? null,
          completedAt: i.completedAt ?? null,
          state: i.state?.name ?? i.state?.type ?? null,
        })
      ),
      completed_projects: linearData.completedProjects.map((p) => {
        const scope = Math.round(p.scope ?? 0);
        return {
          identifier: "Project",
          title: p.name ?? "",
          project: p.name ?? null,
          url: p.url ?? null,
          completedAt: p.completedAt ?? null,
          state: p.status?.name ?? p.status?.type ?? null,
          description: p.description ?? null,
          startedAt: p.startedAt ?? p.startDate ?? null,
          targetDate: p.targetDate ?? null,
          lead: p.lead?.name ?? null,
          issue_count: scope,
          completed_issue_count: Math.round(scope * (p.progress ?? 0)),
        };
      }),
      worked_on_issues: linearData.workedOnIssues.map((i: LinearIssueNode) => ({
        identifier: i.identifier ?? "",
        title: i.title ?? "",
        project: i.project?.name ?? null,
        url: i.url ?? null,
        completedAt: i.completedAt ?? null,
        state: i.state?.name ?? i.state?.type ?? null,
      })),
      created_issues: linearData.createdIssues.map((i: LinearIssueNode) => ({
        identifier: i.identifier ?? "",
        title: i.title ?? "",
        project: i.project?.name ?? null,
        url: i.url ?? null,
        createdAt: i.createdAt ?? null,
        state: i.state?.name ?? i.state?.type ?? null,
      })),
      commented_issues: linearData.commentedIssues,
    },
    github: {
      merged_prs: prCategories.merged.map(
        (pr: {
          title?: string;
          html_url?: string;
          merged_at?: string | null;
          additions?: number;
          deletions?: number;
          changed_files?: number;
        }) => {
          const m = pr.html_url?.match(/ApollosProject\/([^/]+)/);
          return {
            title: pr.title ?? "",
            url: pr.html_url ?? "",
            repo: m ? m[1] : null,
            merged_at: pr.merged_at ?? null,
            additions: pr.additions ?? 0,
            deletions: pr.deletions ?? 0,
            changed_files: pr.changed_files ?? 0,
          };
        }
      ),
      open_prs: prCategories.open.map(
        (pr: { title?: string; html_url?: string; state?: string | null }) => {
          const m = pr.html_url?.match(/ApollosProject\/([^/]+)/);
          return {
            title: pr.title ?? "",
            url: pr.html_url ?? "",
            repo: m ? m[1] : null,
            state: pr.state ?? null,
          };
        }
      ),
      reviews: githubData.reviews as ReviewEntry[],
    },
    check_ins: checkIns,
    terminal_output: terminalOutput,
    formatted_output: null,
  };

  return {
    payload,
    terminalOutput,
    formattedOutput: null,
  };
}
